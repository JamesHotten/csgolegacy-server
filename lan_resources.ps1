[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ServerDir,
    [string]$BindAddress,
    [ValidateRange(1024, 65535)][int]$Port = 27080,
    [switch]$Serve
)

$ErrorActionPreference = 'Stop'
$ServerDir = [IO.Path]::GetFullPath($ServerDir)
$assetRoot = [IO.Path]::GetFullPath((Join-Path $ServerDir 'csgo'))
if (-not (Test-Path -LiteralPath $assetRoot -PathType Container)) { throw 'CS:GO directory not found.' }
if ([string]::IsNullOrWhiteSpace($BindAddress)) {
    $addresses = Get-NetIPConfiguration | Where-Object {
        $_.IPv4DefaultGateway -and $_.NetAdapter.Status -eq 'Up' -and
        $_.InterfaceAlias -notmatch 'vEthernet|VMware|VirtualBox|VPN|Mihomo'
    } | ForEach-Object { $_.IPv4Address.IPAddress } | Where-Object {
        $_ -match '^(10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.)'
    }
    $BindAddress = @($addresses)[0]
    if (-not $BindAddress) { throw 'No private LAN IPv4 address found; pass -BindAddress explicitly.' }
}
$ip = [Net.IPAddress]::Parse($BindAddress)
if ($ip.AddressFamily -ne [Net.Sockets.AddressFamily]::InterNetwork) { throw 'Use an IPv4 LAN address.' }
$baseUrl = 'http://{0}:{1}' -f $BindAddress, $Port
$runtimeDir = Join-Path $ServerDir 'csgo\addons\sourcemod\data\lan-resources'
New-Item -ItemType Directory -Path $runtimeDir -Force | Out-Null

if (-not $Serve) {
    # Probe an actual asset and a private path before advertising this service.
    Add-Type -AssemblyName System.Net.Http
    $handler = [Net.Http.HttpClientHandler]::new()
    $handler.UseProxy = $false
    $http = [Net.Http.HttpClient]::new($handler)
    $http.Timeout = [TimeSpan]::FromSeconds(2)
    $sample = Get-ChildItem -LiteralPath (Join-Path $assetRoot 'materials\panorama\images\tournaments\teams') -Filter '*.svg' | Select-Object -First 1
    if (-not $sample) { throw 'No team logo asset available to verify the download service.' }
    $samplePath = 'materials/panorama/images/tournaments/teams/' + $sample.Name
    $expected = [Convert]::ToBase64String([IO.File]::ReadAllBytes($sample.FullName))
    $ready = $false
    try {
        try {
            $response = $http.GetAsync("$baseUrl/$samplePath").GetAwaiter().GetResult()
            $ready = $response.IsSuccessStatusCode -and
                $response.Headers.Contains('X-CSGOLegacy-Resources') -and
                [Convert]::ToBase64String($response.Content.ReadAsByteArrayAsync().GetAwaiter().GetResult()) -eq $expected
            $response.Dispose()
        } catch { }
        if (-not $ready) {
            if (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue) {
                throw "TCP $Port is already listening, but the expected asset service could not be verified."
            }
            $shellExe = (Get-Process -Id $PID).Path
            $arguments = '-NoProfile -ExecutionPolicy Bypass -File "{0}" -ServerDir "{1}" -BindAddress {2} -Port {3} -Serve' -f $PSCommandPath, $ServerDir, $BindAddress, $Port
            $worker = Start-Process -FilePath $shellExe -ArgumentList $arguments -WindowStyle Hidden -PassThru `
                -RedirectStandardOutput (Join-Path $runtimeDir 'requests.log') `
                -RedirectStandardError (Join-Path $runtimeDir 'errors.log')
            for ($attempt = 0; $attempt -lt 20 -and -not $ready; $attempt++) {
                Start-Sleep -Milliseconds 200
                try {
                    $response = $http.GetAsync("$baseUrl/$samplePath").GetAwaiter().GetResult()
                    $ready = $response.IsSuccessStatusCode -and $response.Headers.Contains('X-CSGOLegacy-Resources') -and
                        [Convert]::ToBase64String($response.Content.ReadAsByteArrayAsync().GetAwaiter().GetResult()) -eq $expected
                    $response.Dispose()
                } catch { }
                if ($worker.HasExited) { break }
            }
            if (-not $ready) { throw "Resource service did not start. Check $runtimeDir\errors.log (port may be occupied)." }
        }
        $private = $http.GetAsync("$baseUrl/cfg/server.cfg").GetAwaiter().GetResult()
        try { if ([int]$private.StatusCode -ne 404) { throw 'Resource service exposed a private path; not advertising it.' } } finally { $private.Dispose() }
        $generated = "// Generated by lan_resources.ps1; read-only LAN asset downloads.`r`nsv_allowdownload 1`r`nsv_downloadurl `"$baseUrl`"`r`n"
        [IO.File]::WriteAllText((Join-Path $assetRoot 'cfg\lan_resources.cfg'), $generated, [Text.Encoding]::ASCII)
        Write-Host "LAN resource downloads ready: $baseUrl"
    } finally { $http.Dispose(); $handler.Dispose() }
    return
}

function Read-HttpLine([IO.Stream]$Stream, [ref]$Remaining) {
    $line = [Text.StringBuilder]::new()
    while ($Remaining.Value -gt 0) {
        $byte = $Stream.ReadByte()
        if ($byte -lt 0) { throw 'Unexpected end of HTTP headers.' }
        $Remaining.Value--
        if ($byte -eq 10) { return $line.ToString().TrimEnd([char]13) }
        [void]$line.Append([char]$byte)
    }
    throw 'HTTP headers exceed 16 KiB.'
}

function Write-Headers([IO.Stream]$Stream, [string]$Status, [long]$Length, [string]$ContentType) {
    $headers = "HTTP/1.1 $Status`r`nContent-Length: $Length`r`nContent-Type: $ContentType`r`nConnection: close`r`nX-CSGOLegacy-Resources: 1`r`n`r`n"
    $bytes = [Text.Encoding]::ASCII.GetBytes($headers)
    $Stream.Write($bytes, 0, $bytes.Length)
}

$listener = [Net.Sockets.TcpListener]::new($ip, $Port)
$listener.Start()
Write-Output "LAN assets listening at $baseUrl"
try {
    while ($true) {
        $client = $listener.AcceptTcpClient()
        try {
            $stream = $client.GetStream()
            $stream.ReadTimeout = 5000
            $stream.WriteTimeout = 10000
            $remaining = 16384
            $request = Read-HttpLine $stream ([ref]$remaining)
            do { $header = Read-HttpLine $stream ([ref]$remaining) } while ($header.Length -gt 0)
            $match = [regex]::Match($request, '^(GET|HEAD) (/[^ ]*) HTTP/1\.[01]$')
            if (-not $match.Success) { Write-Headers $stream '400 Bad Request' 0 'text/plain'; continue }
            $method = $match.Groups[1].Value
            $path = [Uri]::UnescapeDataString(($match.Groups[2].Value -split '\?',2)[0]).TrimStart('/')
            # Only game assets: never publish configs, SQLite, plugins or directory listings.
            $extension = [IO.Path]::GetExtension($path).ToLowerInvariant()
            if ($extension -eq '.bz2') { $extension = [IO.Path]::GetExtension($path.Substring(0,$path.Length-4)).ToLowerInvariant() }
            $allowed = $path -match '^(materials/|models/|sound/|maps/|particles/|resource/flash/)' -and
                $path -match '^[A-Za-z0-9_./ -]+$' -and $path -notmatch '(^|/)\.\.?(/|$)' -and
                $extension -in @('.svg','.png','.vtf','.vmt','.mdl','.vvd','.vtx','.phy','.wav','.mp3','.ogg','.bsp','.nav','.pcf')
            if (-not $allowed) { Write-Headers $stream '404 Not Found' 0 'text/plain'; continue }
            $file = [IO.Path]::GetFullPath((Join-Path $assetRoot ($path.Replace('/','\'))))
            $contained = $file.StartsWith($assetRoot + '\', [StringComparison]::OrdinalIgnoreCase)
            $safe = $contained -and (Test-Path -LiteralPath $file -PathType Leaf)
            if ($safe) {
                $entry = Get-Item -LiteralPath $file
                $directory = $entry.Directory
                while ($directory -and $directory.FullName.Length -ge $assetRoot.Length) {
                    if (($directory.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { $safe = $false; break }
                    $directory = $directory.Parent
                }
                if (($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { $safe = $false }
            }
            if (-not $safe) { Write-Headers $stream '404 Not Found' 0 'text/plain'; continue }
            $inputFile = [IO.File]::Open($file, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite)
            try {
                $contentType = 'application/octet-stream'
                if ($path.EndsWith('.svg')) { $contentType = 'image/svg+xml' }
                if ($path.EndsWith('.png')) { $contentType = 'image/png' }
                Write-Headers $stream '200 OK' $inputFile.Length $contentType
                if ($method -eq 'GET') { $inputFile.CopyTo($stream) }
            } finally { $inputFile.Dispose() }
            Write-Output ('{0:s} {1} 200 {2}' -f (Get-Date), $client.Client.RemoteEndPoint, $path)
        } catch { Write-Output ('{0:s} request ended: {1}' -f (Get-Date), $_.Exception.Message) }
        finally { $client.Dispose() }
    }
} finally { $listener.Stop() }
